def seoul_day_start():
    """한국 시각 기준 오늘 0시."""
    return "date_trunc('day', now() AT TIME ZONE %s)" % SEOUL


def seoul_weekday(dow, hour, past=False):
    """한국 시각으로 다음(또는 지난) 해당 요일 hour시를 timestamptz로 돌려준다.
    오늘은 고르지 않으므로 1~7일 뒤(앞)가 된다."""
    isodow = "EXTRACT(ISODOW FROM now() AT TIME ZONE %s)::int" % SEOUL
    if past:
        days = "(((%s - %d + 6) %% 7) + 1)" % (isodow, dow)
        sign = '-'
    else:
        days = "(((%d - %s + 6) %% 7) + 1)" % (dow, isodow)
        sign = '+'
    return "((%s %s %s * interval '1 day' + interval '%d hours') AT TIME ZONE %s)" % (
        seoul_day_start(), sign, days, hour, SEOUL)


def seoul_offset(days, hour):
    """한국 시각으로 오늘에서 days만큼 떨어진 날의 hour시."""
    sign = '+' if days >= 0 else '-'
    return "((%s %s interval '%d days' + interval '%d hours') AT TIME ZONE %s)" % (
        seoul_day_start(), sign, abs(days), hour, SEOUL)


def literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def user(number):
    return '(SELECT id FROM users WHERE intra_id = %d)' % (-420000 - number)


def club(name):
    return '(SELECT id FROM clubs WHERE name = %s)' % literal('[DEMO] ' + name)


def gathering(title):
    return '(SELECT id FROM gatherings WHERE title = %s)' % literal('[DEMO] ' + title)


def image_key(slug, period):
    return 'activities/%s.png' % uuid.uuid5(NAMESPACE, slug + ':' + period)


def insert_once(table, columns, values, match):
    return 'INSERT INTO %s (%s)\nSELECT %s\nWHERE NOT EXISTS (SELECT 1 FROM %s WHERE %s);' % (
        table, columns, values, table, match)


