CREATE TABLE clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    summary VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    operation_status VARCHAR(20) NOT NULL,
    recruitment_planned BOOLEAN NOT NULL DEFAULT false,
    recruitment_start_date DATE,
    recruitment_end_date DATE,
    recruitment_closed_early BOOLEAN NOT NULL DEFAULT false,
    application_method TEXT,
    application_url VARCHAR(2048),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_clubs_operation_status
        CHECK (operation_status IN ('ACTIVE', 'DORMANT', 'ARCHIVED')),
    CONSTRAINT ck_clubs_recruitment_required
        CHECK (NOT recruitment_planned OR
            (recruitment_start_date IS NOT NULL AND application_method IS NOT NULL)),
    CONSTRAINT ck_clubs_recruitment_dates
        CHECK (recruitment_end_date IS NULL OR
            (recruitment_start_date IS NOT NULL AND recruitment_end_date >= recruitment_start_date)),
    CONSTRAINT ck_clubs_recruitment_closed
        CHECK (NOT recruitment_closed_early OR recruitment_planned)
);
