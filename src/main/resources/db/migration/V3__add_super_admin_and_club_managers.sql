ALTER TABLE users DROP CONSTRAINT ck_users_role;
ALTER TABLE users ADD CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN', 'SUPER_ADMIN'));

CREATE TABLE club_managers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    club_id BIGINT NOT NULL REFERENCES clubs (id),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_club_managers_user_club UNIQUE (user_id, club_id)
);
CREATE INDEX idx_club_managers_club_id ON club_managers (club_id);
