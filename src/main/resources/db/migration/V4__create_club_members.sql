CREATE TABLE club_members (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id), club_id BIGINT NOT NULL REFERENCES clubs(id),
 status VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE','LEFT')),
 approved_by BIGINT NOT NULL REFERENCES users(id), joined_at TIMESTAMPTZ NOT NULL,
 left_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 UNIQUE(user_id,club_id),
 CHECK ((status = 'ACTIVE' AND left_at IS NULL) OR (status = 'LEFT' AND left_at IS NOT NULL)),
 CHECK (left_at IS NULL OR left_at >= joined_at)
);
CREATE INDEX idx_club_members_club_status ON club_members(club_id,status);
