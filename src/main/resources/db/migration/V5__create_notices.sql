CREATE TABLE notices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 club_id BIGINT NOT NULL REFERENCES clubs(id), author_id BIGINT NOT NULL REFERENCES users(id),
 title VARCHAR(200) NOT NULL, content TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, deleted_at TIMESTAMPTZ
);
CREATE INDEX idx_notices_club_created ON notices(club_id,created_at DESC,id DESC);
