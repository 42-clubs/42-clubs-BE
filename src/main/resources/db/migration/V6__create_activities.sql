CREATE TABLE activities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 club_id BIGINT NOT NULL REFERENCES clubs(id), author_id BIGINT NOT NULL REFERENCES users(id),organizer_id BIGINT NOT NULL REFERENCES users(id),
 title VARCHAR(200) NOT NULL,content TEXT NOT NULL,starts_at TIMESTAMPTZ NOT NULL,recruitment_closes_at TIMESTAMPTZ NOT NULL,
 capacity INTEGER NOT NULL CHECK(capacity>=1),created_at TIMESTAMPTZ NOT NULL,updated_at TIMESTAMPTZ NOT NULL,deleted_at TIMESTAMPTZ,
 CHECK(author_id=organizer_id),CHECK(recruitment_closes_at<starts_at)
);
CREATE INDEX idx_activities_club_starts ON activities(club_id,starts_at,id);
CREATE TABLE activity_images (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,activity_id BIGINT NOT NULL REFERENCES activities(id),
 storage_key TEXT NOT NULL UNIQUE,sort_order INTEGER NOT NULL CHECK(sort_order>=0),created_at TIMESTAMPTZ NOT NULL,UNIQUE(activity_id,sort_order)
);
CREATE TABLE image_uploads (storage_key TEXT PRIMARY KEY,created_at TIMESTAMPTZ NOT NULL);
CREATE INDEX idx_image_uploads_created ON image_uploads(created_at);
CREATE TABLE activity_participants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,activity_id BIGINT NOT NULL REFERENCES activities(id),user_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('CONFIRMED','CANCELLED')),
 attendance_status VARCHAR(20) NOT NULL DEFAULT 'UNCHECKED' CHECK(attendance_status IN ('UNCHECKED','PRESENT')),
 attendance_checked_by BIGINT REFERENCES users(id),attendance_checked_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL,updated_at TIMESTAMPTZ NOT NULL,UNIQUE(activity_id,user_id),
 CHECK((attendance_status='UNCHECKED' AND attendance_checked_by IS NULL AND attendance_checked_at IS NULL) OR (attendance_status='PRESENT' AND attendance_checked_by IS NOT NULL AND attendance_checked_at IS NOT NULL))
);
CREATE INDEX idx_activity_participants_user ON activity_participants(user_id);
