CREATE TABLE gatherings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,organizer_id BIGINT NOT NULL REFERENCES users(id),title VARCHAR(200) NOT NULL,content TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,updated_at TIMESTAMPTZ NOT NULL,deleted_at TIMESTAMPTZ
);
CREATE INDEX idx_gatherings_organizer ON gatherings(organizer_id);
CREATE TABLE gathering_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,gathering_id BIGINT NOT NULL REFERENCES gatherings(id),starts_at TIMESTAMPTZ NOT NULL,ends_at TIMESTAMPTZ NOT NULL,
 recruitment_opens_at TIMESTAMPTZ NOT NULL,recruitment_closes_at TIMESTAMPTZ NOT NULL,location VARCHAR(255) NOT NULL,capacity INTEGER NOT NULL CHECK(capacity>=1),
 cancelled_at TIMESTAMPTZ,created_at TIMESTAMPTZ NOT NULL,updated_at TIMESTAMPTZ NOT NULL,
 CHECK(ends_at>starts_at),CHECK(recruitment_opens_at<=starts_at - INTERVAL '2 hours'),CHECK(recruitment_opens_at<recruitment_closes_at AND recruitment_closes_at<starts_at)
);
CREATE INDEX idx_gathering_sessions_gathering_starts ON gathering_sessions(gathering_id,starts_at,id);
CREATE TABLE gathering_session_participants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id BIGINT NOT NULL REFERENCES gathering_sessions(id),user_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL CHECK(status IN ('CONFIRMED','CANCELLED')),
 attendance_status VARCHAR(20) NOT NULL DEFAULT 'UNCHECKED' CHECK(attendance_status IN ('UNCHECKED','PRESENT')),
 attendance_checked_by BIGINT REFERENCES users(id),attendance_checked_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL,updated_at TIMESTAMPTZ NOT NULL,UNIQUE(session_id,user_id),
 CHECK((attendance_status='UNCHECKED' AND attendance_checked_by IS NULL AND attendance_checked_at IS NULL) OR (attendance_status='PRESENT' AND attendance_checked_by IS NOT NULL AND attendance_checked_at IS NOT NULL))
);
CREATE INDEX idx_gathering_session_participants_user ON gathering_session_participants(user_id);
